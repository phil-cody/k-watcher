/**
 * Контракт текстов: какие ключи использует код и какие плейсхолдеры в них ожидаются.
 *
 * Это «живая спецификация» текстов. Тест `test/texts.test.js` сверяет контракт с
 * config/texts.json, поэтому:
 *   - нельзя удалить нужный код текст, не заметив этого;
 *   - нельзя потерять плейсхолдер ({count}) при правке формулировки;
 *   - появившийся в шаблоне лишний/неизвестный плейсхолдер виден сразу.
 *
 * Если добавляете новый текст в код — добавьте путь сюда.
 */

/** Найти плейсхолдеры вида {name} в шаблоне. */
export function findPlaceholders(template) {
  const found = new Set();
  for (const match of String(template ?? '').matchAll(/\{(\w+)\}/g)) found.add(match[1]);
  return [...found].sort();
}

